import type { RepoAnalysis } from "@/types";

const NODE_IMAGE = "node:22-alpine";
const BUN_IMAGE = "oven/bun:1";
const DEFAULT_PORT = 3000;

const STATIC_FRAMEWORKS = new Set(["React", "Vue", "Svelte", "Astro", "Gatsby"]);
const SERVER_FRAMEWORKS = new Set(["Next.js", "Nuxt", "Remix"]);

// Frameworks whose production entry point is fixed even when package.json
// has no start script. Anything else without a start script has nothing
// reliable for the container to run, so no Dockerfile is generated.
const FRAMEWORK_START_COMMANDS: Record<string, string[]> = {
  "Next.js": ["./node_modules/.bin/next", "start"],
  Nuxt: ["node", ".output/server/index.mjs"],
};

type AppKind = "server" | "static";

/**
 * A Dockerfile is generated when the repo is a Node-based app (a package.json
 * was found during analysis) and it does not already have one. Shipwright
 * never overwrites an existing Dockerfile.
 */
export function shouldGenerateDockerfile(analysis: RepoAnalysis): boolean {
  if (analysis.hasDocker) {
    return false;
  }

  return !analysis.deploymentIssues.some((issue) => issue.title === "No package.json found");
}

export function generateDockerfile(analysis: RepoAnalysis): string | null {
  if (!shouldGenerateDockerfile(analysis)) {
    return null;
  }

  const kind = getAppKind(analysis);
  if (!kind) {
    return null;
  }

  if (kind === "static") {
    if (!analysis.buildScript) {
      return null;
    }
    return buildStaticDockerfile(analysis);
  }

  const startCommand = getStartCommand(analysis);
  if (!startCommand) {
    return null;
  }

  return buildServerDockerfile(analysis, startCommand);
}

export function generateDockerignore(analysis: RepoAnalysis): string | null {
  if (!shouldGenerateDockerfile(analysis)) {
    return null;
  }

  return [
    "# Generated by Shipwright",
    "node_modules",
    ".git",
    ".github",
    ".next",
    ".output",
    "dist",
    "build",
    "coverage",
    ".turbo",
    ".vercel",
    ".env",
    ".env.*",
    "!.env.example",
    "*.log",
    "npm-debug.log*",
    ".DS_Store",
    "Dockerfile",
    ".dockerignore",
    "",
  ].join("\n");
}

function getAppKind(analysis: RepoAnalysis): AppKind | null {
  if (analysis.backendType !== "Frontend") {
    return "server";
  }

  if (SERVER_FRAMEWORKS.has(analysis.framework)) {
    return "server";
  }

  if (STATIC_FRAMEWORKS.has(analysis.framework)) {
    // A start script on a static framework usually means a custom or SSR
    // server entry point, so treat the app as a server in that case.
    return analysis.startScript ? "server" : "static";
  }

  return analysis.startScript ? "server" : null;
}

function getStartCommand(analysis: RepoAnalysis): string[] | null {
  if (analysis.startScript) {
    switch (analysis.packageManager) {
      case "yarn":
        return ["yarn", "start"];
      case "pnpm":
        return ["pnpm", "start"];
      case "bun":
        return ["bun", "run", "start"];
      default:
        return ["npm", "start"];
    }
  }

  return FRAMEWORK_START_COMMANDS[analysis.framework] ?? null;
}

function getBaseImage(analysis: RepoAnalysis): string {
  return analysis.packageManager === "bun" ? BUN_IMAGE : NODE_IMAGE;
}

function getRuntimeUser(analysis: RepoAnalysis): string {
  return analysis.packageManager === "bun" ? "bun" : "node";
}

function getInstallSetup(analysis: RepoAnalysis): {
  manifestFiles: string;
  setupLines: string[];
  installLine: string;
  pruneLine: string | null;
} {
  switch (analysis.packageManager) {
    case "pnpm":
      return {
        manifestFiles: "package.json pnpm-lock.yaml*",
        setupLines: ["RUN corepack enable"],
        installLine:
          "RUN if [ -f pnpm-lock.yaml ]; then pnpm install --frozen-lockfile; else pnpm install; fi",
        pruneLine: "RUN pnpm prune --prod",
      };
    case "yarn":
      return {
        manifestFiles: "package.json yarn.lock*",
        setupLines: ["RUN corepack enable"],
        installLine:
          "RUN if [ -f yarn.lock ]; then yarn install --frozen-lockfile; else yarn install; fi",
        pruneLine: null,
      };
    case "bun":
      return {
        manifestFiles: "package.json bun.lock*",
        setupLines: [],
        installLine:
          "RUN if [ -f bun.lock ]; then bun install --frozen-lockfile; else bun install; fi",
        pruneLine: null,
      };
    default:
      return {
        manifestFiles: "package.json package-lock.json*",
        setupLines: [],
        installLine: "RUN if [ -f package-lock.json ]; then npm ci; else npm install; fi",
        pruneLine: "RUN npm prune --omit=dev",
      };
  }
}

function getBuildCommand(analysis: RepoAnalysis): string {
  switch (analysis.packageManager) {
    case "yarn":
      return "yarn build";
    case "pnpm":
      return "pnpm run build";
    case "bun":
      return "bun run build";
    default:
      return "npm run build";
  }
}

function getStaticOutputDir(analysis: RepoAnalysis): string {
  const buildScript = analysis.buildScript || "";

  if (buildScript.includes("gatsby")) return "public";
  if (buildScript.includes("astro")) return "dist";
  if (buildScript.includes("vite")) return "dist";
  if (buildScript.includes("react-scripts")) return "build";

  switch (analysis.framework) {
    case "Gatsby":
      return "public";
    case "Astro":
    case "Vue":
    case "Svelte":
      return "dist";
    case "React":
      return "build";
    default:
      return "dist";
  }
}

function headerLines(analysis: RepoAnalysis): string[] {
  return [
    "# Generated by Shipwright — production Dockerfile",
    `# Detected: ${analysis.framework} app, ${analysis.packageManager} package manager, ${analysis.backendType} backend`,
  ];
}

function buildServerDockerfile(analysis: RepoAnalysis, startCommand: string[]): string {
  const baseImage = getBaseImage(analysis);
  const install = getInstallSetup(analysis);
  const lines: string[] = [
    ...headerLines(analysis),
    "# Build: docker build -t app .",
    `# Run:   docker run -p ${DEFAULT_PORT}:${DEFAULT_PORT} --env-file .env app`,
    "",
    `FROM ${baseImage} AS deps`,
    "WORKDIR /app",
    ...install.setupLines,
    `COPY ${install.manifestFiles} ./`,
    install.installLine,
    "",
    `FROM ${baseImage} AS build`,
    "WORKDIR /app",
    ...install.setupLines,
    "COPY --from=deps /app/node_modules ./node_modules",
    "COPY . .",
  ];

  if (analysis.buildScript) {
    lines.push(`RUN ${getBuildCommand(analysis)}`);
  }
  if (install.pruneLine) {
    lines.push(install.pruneLine);
  }

  lines.push(
    "",
    `FROM ${baseImage} AS runner`,
    "ENV NODE_ENV=production",
    `ENV PORT=${DEFAULT_PORT}`,
    "WORKDIR /app",
    "COPY --from=build /app ./",
    `USER ${getRuntimeUser(analysis)}`,
    `EXPOSE ${DEFAULT_PORT}`,
    `CMD ${formatCommand(startCommand)}`,
    ""
  );

  return lines.join("\n");
}

function buildStaticDockerfile(analysis: RepoAnalysis): string {
  const baseImage = getBaseImage(analysis);
  const install = getInstallSetup(analysis);
  const outputDir = getStaticOutputDir(analysis);

  return [
    ...headerLines(analysis),
    "# Build: docker build -t app .",
    "# Run:   docker run -p 8080:80 app",
    "# Note: single-page apps may need a rewrite rule so client-side routes",
    "# resolve to index.html; the default nginx config serves files as-is.",
    "",
    `FROM ${baseImage} AS build`,
    "WORKDIR /app",
    ...install.setupLines,
    `COPY ${install.manifestFiles} ./`,
    install.installLine,
    "COPY . .",
    `RUN ${getBuildCommand(analysis)}`,
    "",
    "FROM nginx:alpine AS runner",
    `COPY --from=build /app/${outputDir} /usr/share/nginx/html`,
    "EXPOSE 80",
    `CMD ${formatCommand(["nginx", "-g", "daemon off;"])}`,
    "",
  ].join("\n");
}

function formatCommand(command: string[]): string {
  return `[${command.map((part) => JSON.stringify(part)).join(", ")}]`;
}
