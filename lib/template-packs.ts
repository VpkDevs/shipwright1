import type { RepoAnalysis } from "@/types";

export const TEMPLATE_PACK_IDS = ["default", "saas", "oss", "api", "portfolio"] as const;
export type TemplatePackId = (typeof TEMPLATE_PACK_IDS)[number];

export interface PackCopy {
  readmeTagline: string;
  readmeAudience: string;
  landingHeadline: string;
  landingSubhead: string;
  landingCtaPrimary: string;
  landingCtaSecondary: string;
}

export function normalizeTemplatePack(raw: string | undefined): TemplatePackId {
  if (!raw) return "default";
  const lower = raw.toLowerCase().trim();
  if (TEMPLATE_PACK_IDS.includes(lower as TemplatePackId)) {
    return lower as TemplatePackId;
  }
  return "default";
}

export function getPackCopy(
  pack: TemplatePackId,
  repoName: string,
  analysis: RepoAnalysis
): PackCopy {
  const stack = `${analysis.framework} · ${analysis.packageManager}`;

  const bases: Record<TemplatePackId, Omit<PackCopy, never>> = {
    default: {
      readmeTagline: "Ship-ready handoff generated by Shipwright.",
      readmeAudience: "Developers and reviewers who need a clear launch picture.",
      landingHeadline: repoName,
      landingSubhead: analysis.description || "A focused build with deployment scaffolding.",
      landingCtaPrimary: "View on GitHub",
      landingCtaSecondary: "Documentation",
    },
    saas: {
      readmeTagline: "Product-focused README for a SaaS-style launch.",
      readmeAudience: "Founders, customers, and teammates evaluating the product.",
      landingHeadline: `${repoName} — ship the workflow`,
      landingSubhead: `${stack}. Built for teams who need credible packaging before going live.`,
      landingCtaPrimary: "Get started",
      landingCtaSecondary: "See pricing",
    },
    oss: {
      readmeTagline: "Contributor-friendly overview for open source.",
      readmeAudience: "Contributors, maintainers, and downstream users.",
      landingHeadline: `${repoName}`,
      landingSubhead: `Open, fork-friendly project. ${analysis.description || "Community-driven development."}`,
      landingCtaPrimary: "Contribute",
      landingCtaSecondary: "Report issue",
    },
    api: {
      readmeTagline: "API and backend-oriented documentation tone.",
      readmeAudience: "Integrators and backend engineers wiring services.",
      landingHeadline: `${repoName} API`,
      landingSubhead: `${stack}. Endpoints, env, and deploy path summarized for integration teams.`,
      landingCtaPrimary: "API docs",
      landingCtaSecondary: "Health check",
    },
    portfolio: {
      readmeTagline: "Showcase tone for portfolios and personal sites.",
      readmeAudience: "Hiring managers and collaborators browsing your work.",
      landingHeadline: repoName,
      landingSubhead:
        analysis.description || "Selected work — optimized for a sharp first impression.",
      landingCtaPrimary: "Contact",
      landingCtaSecondary: "Resume",
    },
  };

  return bases[pack];
}
